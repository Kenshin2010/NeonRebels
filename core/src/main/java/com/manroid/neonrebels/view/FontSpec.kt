package com.manroid.neonrebels.view

/**
 * Baked UI font produced by scripts/generate-font.py. Layout scales throughout the UI were
 * tuned for a 15px font, so text scales are multiplied by [UNIT] to keep the same visual size.
 */
object FontSpec {
    const val FILE = "fonts/neon-ui.fnt"
    const val ITALIC_FILE = "fonts/neon-italic.fnt"
    const val PIXEL_SIZE = 42f
    const val DESIGN_SIZE = 15f
    const val UNIT = DESIGN_SIZE / PIXEL_SIZE
}
